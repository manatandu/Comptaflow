type LigneSeed = {
  numero: string;
  intitule: string;
  classe: ClasseCompte;
  modeReportANouveau: ModeReportANouveau;
  typeCompte?: TypeCompteDetailTotal;
};

/** Compte d'imputation · numéro complété à 8 chiffres, type Détail. */
function d(numero: string, intitule: string, classe: ClasseCompte, mode: ModeReportANouveau): LigneSeed {
  return { numero, intitule, classe, modeReportANouveau: mode };
}

/** En-tête de regroupement · numéro officiel non complété, type TOTAL. */
function t(numero: string, intitule: string, classe: ClasseCompte, mode: ModeReportANouveau): LigneSeed {
  return { numero, intitule, classe, modeReportANouveau: mode, typeCompte: TypeCompteDetailTotal.TOTAL };
}

